#!/usr/bin/env python3
"""Merge docs/batches/*.json into src/data/{graph,places,glossary}.json and collect open issues.
Idempotent: safe to run repeatedly. Batches may also carry nodes_remove (ids), edges_remove ({from,to}), places_remove ({name,figure}), glossary_remove (terms) and glossary_update. A nodes_update entry may carry "unset": [field, ...] to delete fields. Usage: python3 scripts/merge-batches.py [batch-id ...]"""
import json, sys, glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)

def load(p): return json.load(open(p, encoding='utf-8'))
def save(p, d): json.dump(d, open(p, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)

graph, places, gloss = load(P('src/data/graph.json')), load(P('src/data/places.json')), load(P('src/data/glossary.json'))
files = sorted(glob.glob(P('docs/batches/*.json')))
if len(sys.argv) > 1: files = [f for f in files if os.path.basename(f)[:-5] in sys.argv[1:]]

ids = {n['id']: n for n in graph['nodes']}
issues = []
art = []
for f in files:
    b = load(f); bid = b.get('batch', os.path.basename(f)[:-5])
    for n in b.get('nodes_add', []):
        if n['id'] in ids: ids[n['id']].update({k: v for k, v in n.items() if v is not None})
        else: graph['nodes'].append(n); ids[n['id']] = n
    for u in b.get('nodes_update', []):
        if u['id'] in ids:
            ids[u['id']].update({k: v for k, v in u.items() if v is not None and k != 'unset'})
            for k in u.get('unset', []): ids[u['id']].pop(k, None)
        else: issues.append(f"[{bid}] nodes_update for unknown id {u['id']}")
    nrm = set(b.get('nodes_remove', []))
    if nrm:
        graph['nodes'] = [n for n in graph['nodes'] if n['id'] not in nrm]
        for i in nrm: ids.pop(i, None)
        graph['edges'] = [e for e in graph['edges'] if e['from'] not in nrm and e['to'] not in nrm]
    rm = {(e['from'], e['to']) for e in b.get('edges_remove', [])}
    graph['edges'] = [e for e in graph['edges'] if (e['from'], e['to']) not in rm]
    for e in b.get('edges_upsert', []):
        if e['from'] not in ids or e['to'] not in ids:
            issues.append(f"[{bid}] edge {e['from']} -> {e['to']} references a missing node"); continue
        found = [x for x in graph['edges'] if x['from'] == e['from'] and x['to'] == e['to']]
        if found: found[0].clear(); found[0].update(e)
        else: graph['edges'].append(e)
    prm = {(p['name'], p['figure']) for p in b.get('places_remove', [])}
    if prm: places['places'] = [p for p in places['places'] if (p['name'], p['figure']) not in prm]
    have = {(p['name'], p['figure']) for p in places['places']}
    for p in b.get('places', []):
        if (p['name'], p['figure']) in have:
            for q in places['places']:
                if (q['name'], q['figure']) == (p['name'], p['figure']): q.update(p)
        else: places['places'].append(p)
    grm = {t.lower() for t in b.get('glossary_remove', [])}
    if grm: gloss[:] = [t for t in gloss if t['term'].lower() not in grm]
    terms = {t['term'].lower(): t for t in gloss}
    for t in b.get('glossary_update', []):
        if t['term'].lower() in terms: terms[t['term'].lower()].update(t)
    for t in b.get('glossary', []):
        if t['term'].lower() not in terms: gloss.append(t); terms[t['term'].lower()] = t
    art += b.get('art', [])
    issues += [f"[{bid}] {i}" for i in b.get('issues', [])]
    fc = b.get('factcheck', {})
    issues += [f"[{bid} fact-check] {i}" for i in fc.get('unresolved', [])]

# drop edges whose nodes vanished; dedupe
seen, clean = set(), []
for e in graph['edges']:
    k = (e['from'], e['to'], e.get('type'))
    if e['from'] in ids and e['to'] in ids and k not in seen: seen.add(k); clean.append(e)
graph['edges'] = clean
save(P('src/data/graph.json'), graph); save(P('src/data/places.json'), places); save(P('src/data/glossary.json'), gloss)

# register art components
page = P('src/pages/figures/[id].astro')
src = open(page, encoding='utf-8').read()
for a in art:
    comp = os.path.basename(a['file'])[:-6]
    imp = f"import {comp} from '../../components/art/{comp}.astro';"
    if imp not in src and os.path.exists(P(a['file'])):
        src = src.replace("import { nodes,", imp + "\nimport { nodes,", 1)
        src = re.sub(r"const ART = \{(.*?)\};", lambda m: "const ART = {" + m.group(1) + f", {a['name']}: {comp}" + "};", src, count=1)
open(page, 'w', encoding='utf-8').write(src)

with open(P('docs/OPEN_ISSUES_BATCHES.md'), 'w', encoding='utf-8') as fh:
    fh.write("# Open issues collected from batches\n\nGenerated by scripts/merge-batches.py. Edit docs/OPEN_ISSUES.md for the curated list.\n\n")
    for i in issues: fh.write(f"- {i}\n")
print(f"merged {len(files)} batch file(s): {len(graph['nodes'])} nodes, {len(graph['edges'])} edges "
      f"({sum(1 for e in graph['edges'] if e.get('verified'))} verified), {len(places['places'])} places, {len(gloss)} terms, {len(issues)} issues")
